# 用于记录失败的城市
failed_cities = []

for city in cities:
    print(f"\n{'='*50}")
    print(f"开始处理城市: {city}")
    print('='*50)
    
    # 运行子进程
    result = subprocess.run(
        [sys.executable, 'run_all.py', city],
        capture_output=False
    )
    
    # 检查执行结果
    if result.returncode != 0:
        print(f"⚠️ 城市 {city} 处理失败或不存在，已跳过。")
        failed_cities.append(city)
        continue  # 跳过当前循环，进入下一个城市

